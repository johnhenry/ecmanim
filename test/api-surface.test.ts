// Public export-surface guardrail (epic #61, child #63).
//
// Every subpath in package.json `exports` is imported from `src/` and its
// runtime export surface -- a sorted `name: typeof` map -- is compared with the
// committed `test/api-surface.snapshot.json`:
//   * a REMOVED export or a CHANGED kind (e.g. function -> object) fails: that
//     is a breaking change;
//   * an ADDED export also fails until the snapshot is regenerated on purpose
//     with `UPDATE_API=1 node --test test/api-surface.test.ts`, so every new
//     public export shows up in the PR diff and gets reviewed;
//   * a subpath added to / removed from `exports` fails the same way.
//
// Optional dependencies: a subpath whose import needs an optional package that
// is not installed (three, @dimforge/rapier*, @napi-rs/canvas, ...) cannot be
// introspected. That is handled EXPLICITLY, never silently: the check for that
// subpath is reported as SKIPPED with the reason, and when (re)generating the
// snapshot such a subpath is recorded as `{ "skipped": "<reason>" }` unless a
// real entry is already committed (a real entry is never clobbered by a
// machine that lacks the dep). Any other import failure is a hard failure.
//
// Scope: this covers the RUNTIME surface only (types/interfaces are erased).
// Type shapes are pinned in test/types/api.test-d.ts (run by `npm run
// type-check`).

import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SNAPSHOT_PATH = join(ROOT, "test", "api-surface.snapshot.json");
const UPDATE = process.env.UPDATE_API === "1";

type Surface = Record<string, string>;
type Entry = { exports: Surface } | { skipped: string };
interface Snapshot {
  $comment: string[];
  subpaths: Record<string, Entry>;
}

const COMMENT = [
  "Public runtime export surface of @johnhenry/ecmanim: `name: typeof` per package.json `exports` subpath.",
  "Generated by test/api-surface.test.ts -- do not edit by hand.",
  "Regenerate after a DELIBERATE API change: UPDATE_API=1 node --test test/api-surface.test.ts",
  "Additions are fine (review the diff); removals and kind changes are breaking (see AGENTS.md compatibility rules).",
  "A subpath recorded as { \"skipped\": ... } needs an optional dependency that was not installed when the snapshot was generated.",
];

const UPDATE_HINT =
  "If this change is intentional, regenerate the snapshot and commit it:\n" +
  "    UPDATE_API=1 node --test test/api-surface.test.ts\n" +
  "then check `git diff test/api-surface.snapshot.json` shows ONLY additions.\n" +
  "Removals / kind changes are breaking: do not make them without a deprecation\n" +
  "(src/core/deprecate.ts) and a `Changed (breaking)` CHANGELOG entry.";

/** package.json `exports` -> { subpath: src file }. "./dist/x.js" -> "src/x.ts". */
function readSubpaths(): Record<string, string> {
  const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
  const out: Record<string, string> = {};
  for (const [sub, target] of Object.entries<any>(pkg.exports)) {
    const file: string = typeof target === "string" ? target : target.default ?? target.import;
    const m = /^\.\/dist\/(.+)\.js$/.exec(file);
    assert.ok(m, `exports["${sub}"] -> "${file}" does not look like ./dist/<path>.js`);
    out[sub] = `src/${m![1]}.ts`;
  }
  return out;
}

const sortedKeys = (o: object) => Object.keys(o).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

/** Import one subpath and describe it. Returns a skip reason for missing optional deps. */
async function introspect(srcFile: string): Promise<Entry> {
  let mod: Record<string, unknown>;
  try {
    mod = await import(pathToFileURL(join(ROOT, srcFile)).href);
  } catch (e: any) {
    const pkg = /Cannot find (?:package|module) '([^']+)'/.exec(String(e?.message))?.[1];
    if (e?.code === "ERR_MODULE_NOT_FOUND" && pkg && !pkg.startsWith(".") && !pkg.startsWith("/")) {
      return { skipped: `optional dependency "${pkg}" is not installed` };
    }
    throw new Error(`api-surface: importing ${srcFile} failed (not a missing optional dependency): ${e?.stack ?? e}`);
  }
  const exports: Surface = {};
  for (const name of sortedKeys(mod)) {
    if (name === "default") continue; // ESM namespace `default` only appears for CJS interop
    exports[name] = typeof mod[name];
  }
  return { exports };
}

export interface SurfaceDiff {
  removed: string[];
  added: string[];
  changed: string[];
}

export function diffSurface(expected: Surface, actual: Surface): SurfaceDiff {
  const removed: string[] = [];
  const added: string[] = [];
  const changed: string[] = [];
  for (const name of sortedKeys(expected)) {
    if (!(name in actual)) removed.push(`${name} (${expected[name]})`);
    else if (actual[name] !== expected[name]) changed.push(`${name}: ${expected[name]} -> ${actual[name]}`);
  }
  for (const name of sortedKeys(actual)) if (!(name in expected)) added.push(`${name} (${actual[name]})`);
  return { removed, added, changed };
}

export function formatDiff(subpath: string, d: SurfaceDiff): string {
  const lines = [`Public API surface of "${subpath}" differs from test/api-surface.snapshot.json.`];
  const section = (title: string, items: string[]) => {
    if (items.length) lines.push("", `  ${title} (${items.length}):`, ...items.map((i) => `    - ${i}`));
  };
  section("REMOVED exports -- BREAKING", d.removed);
  section("CHANGED kind -- BREAKING", d.changed);
  section("ADDED exports -- not yet in the snapshot", d.added);
  lines.push("", UPDATE_HINT);
  return lines.join("\n");
}

function loadSnapshot(): Snapshot | undefined {
  try {
    return JSON.parse(readFileSync(SNAPSHOT_PATH, "utf8"));
  } catch (e: any) {
    if (e?.code === "ENOENT") return undefined;
    throw e;
  }
}

function serialize(subpaths: Record<string, Entry>): string {
  const ordered: Record<string, Entry> = {};
  for (const k of sortedKeys(subpaths)) ordered[k] = subpaths[k];
  const snap: Snapshot = { $comment: COMMENT, subpaths: ordered };
  return JSON.stringify(snap, null, 2) + "\n";
}

const SUBPATHS = readSubpaths();
const committed = loadSnapshot();

// Introspect everything once (sequential: these import the whole library, and
// the host may be CPU-shared), up front, so UPDATE_API can write before checks.
const actual: Record<string, Entry> = {};
for (const [sub, file] of Object.entries(SUBPATHS)) actual[sub] = await introspect(file);

if (UPDATE) {
  const next: Record<string, Entry> = {};
  for (const sub of Object.keys(SUBPATHS)) {
    const now = actual[sub];
    const prev = committed?.subpaths[sub];
    // Never replace a real committed surface with a "skipped" marker.
    next[sub] = "skipped" in now && prev && "exports" in prev ? prev : now;
    if ("skipped" in now && prev && "exports" in prev) {
      console.warn(`[api-surface] "${sub}" kept as committed: ${now.skipped}`);
    }
  }
  const text = serialize(next);
  if (text !== (committed ? readFileSync(SNAPSHOT_PATH, "utf8") : "")) {
    writeFileSync(SNAPSHOT_PATH, text);
    console.warn(`[api-surface] UPDATE_API=1: wrote ${SNAPSHOT_PATH}. Review \`git diff\`; removals are breaking.`);
  }
}

const snapshot = UPDATE ? loadSnapshot() : committed;

test("api-surface: snapshot file exists and is canonically formatted", () => {
  assert.ok(snapshot, "test/api-surface.snapshot.json is missing.\n" + UPDATE_HINT);
  assert.equal(
    readFileSync(SNAPSHOT_PATH, "utf8"),
    serialize(snapshot!.subpaths),
    "snapshot is not in canonical (sorted, 2-space) form; regenerate with UPDATE_API=1",
  );
});

test("api-surface: snapshot covers exactly the package.json `exports` subpaths", () => {
  const want = sortedKeys(SUBPATHS);
  const have = sortedKeys(snapshot?.subpaths ?? {});
  const missing = want.filter((s) => !have.includes(s));
  const stale = have.filter((s) => !want.includes(s));
  assert.ok(
    !missing.length && !stale.length,
    `package.json \`exports\` and the snapshot disagree.\n` +
      (missing.length ? `  subpaths not in snapshot: ${missing.join(", ")}\n` : "") +
      (stale.length ? `  subpaths no longer exported (BREAKING): ${stale.join(", ")}\n` : "") +
      UPDATE_HINT,
  );
});

for (const sub of Object.keys(SUBPATHS)) {
  test(`api-surface: ${sub} (${SUBPATHS[sub]})`, (t) => {
    const now = actual[sub];
    const want = snapshot?.subpaths[sub];
    if (!want) return assert.fail(`"${sub}" has no snapshot entry.\n${UPDATE_HINT}`);
    if ("skipped" in now) {
      // Explicit, visible, never a silent pass.
      t.skip(`cannot verify "${sub}": ${now.skipped}`);
      return;
    }
    if ("skipped" in want) {
      // Snapshot generated without the dep, but we can see the surface now.
      return assert.fail(
        `"${sub}" is recorded as skipped (${want.skipped}) but is importable here.\n` +
          `Regenerate on this machine:\n    UPDATE_API=1 node --test test/api-surface.test.ts`,
      );
    }
    const d = diffSurface(want.exports, now.exports);
    assert.ok(!d.removed.length && !d.changed.length && !d.added.length, formatDiff(sub, d));
  });
}

// --- the diff/message helpers themselves ----------------------------------

test("api-surface: diff reports removed / changed / added exactly", () => {
  const d = diffSurface({ a: "function", b: "function", c: "object" }, { a: "function", b: "object", d: "function" });
  assert.deepEqual(d, { removed: ["c (object)"], changed: ["b: function -> object"], added: ["d (function)"] });
});

test("api-surface: failure message names every export and how to update", () => {
  const msg = formatDiff("./x", { removed: ["Foo (function)"], changed: ["Bar: function -> object"], added: ["Baz (function)"] });
  for (const needle of ["\"./x\"", "Foo (function)", "Bar: function -> object", "Baz (function)", "UPDATE_API=1", "BREAKING"]) {
    assert.ok(msg.includes(needle), `message missing ${needle}:\n${msg}`);
  }
});
